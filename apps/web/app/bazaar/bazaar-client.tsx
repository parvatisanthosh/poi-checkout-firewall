"use client";

import { useEffect, useState } from "react";
import { ListingCard, ProductPage } from "@poi/shared";
import { Card, cx, ErrorNote, Pill, Spinner } from "@/components/ui";
import { BAZAAR_PUBLIC_URL } from "@/lib/config";

interface Meta {
  family: string;
  hidden: { text: string; placement: string } | null;
  banner: string | null;
  shippingUsd: number;
  checkoutExtras: {
    lines: Array<{ name: string; unitUsd: number }>;
    feesUsd?: { handling?: number; insurance?: number };
  } | null;
}

const CATEGORIES = ["usb-c hub", "wireless earbuds", "laptop stand"] as const;
const stars = (r: number) => "★★★★★".slice(0, Math.round(r)) + "☆☆☆☆☆".slice(0, 5 - Math.round(r));

export function BazaarClient() {
  const [category, setCategory] = useState<(typeof CATEGORIES)[number]>("usb-c hub");
  const [q, setQ] = useState("");
  const [cards, setCards] = useState<ListingCard[] | null>(null);
  const [open, setOpen] = useState<{ page: ProductPage; meta: Meta } | null>(null);
  const [agentEye, setAgentEye] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    setCards(null);
    const qs = new URLSearchParams({ category, ...(q ? { q } : {}) });
    fetch(`${BAZAAR_PUBLIC_URL}/catalog?${qs}`)
      .then((r) => r.json())
      .then((j) => setCards(ListingCard.array().parse(j)))
      .catch(() =>
        setError(`The Bazaar isn't reachable at ${BAZAAR_PUBLIC_URL}. Start it with pnpm dev.`),
      );
  }, [category, q]);

  const view = async (sku: string) => {
    const [page, meta] = await Promise.all([
      fetch(`${BAZAAR_PUBLIC_URL}/products/${encodeURIComponent(sku)}`).then((r) => r.json()),
      fetch(`${BAZAAR_PUBLIC_URL}/products/${encodeURIComponent(sku)}/meta`).then(
        (r) => r.json() as Promise<Meta>,
      ),
    ]);
    setOpen({ page: ProductPage.parse(page), meta });
    window.scrollTo({ top: 0, behavior: "smooth" });
  };

  return (
    <div className={cx(agentEye && "agent-eye")}>
      <div className="mb-6 flex flex-wrap items-center gap-3">
        {CATEGORIES.map((c) => (
          <button
            key={c}
            onClick={() => {
              setCategory(c);
              setOpen(null);
            }}
            className={cx(
              "rounded-full px-3 py-1 text-sm",
              c === category ? "bg-ink text-panel" : "border border-line text-muted hover:text-ink",
            )}
          >
            {c}
          </button>
        ))}
        <input
          className="ml-auto w-56 rounded-xl border border-line bg-white px-3 py-1.5 text-sm dark:bg-zinc-900"
          placeholder="Search the Bazaar"
          value={q}
          onChange={(e) => setQ(e.target.value)}
        />
      </div>
      <ErrorNote error={error} />

      {open && (
        <div className="mb-8 grid gap-6 lg:grid-cols-[1fr_300px]">
          <Card>
            <button className="mb-3 text-xs text-brand" onClick={() => setOpen(null)}>
              ← Back to results
            </button>
            {/* HTML generated by our Bazaar with every merchant string escaped (render-page.ts). */}
            <div dangerouslySetInnerHTML={{ __html: open.page.pageHtml }} />
          </Card>
          <div className="space-y-4">
            <Card title="Buy box">
              <p className="text-2xl font-semibold">${open.page.card.priceUsd.toFixed(2)}</p>
              <p className="text-xs text-muted">
                {open.meta.shippingUsd
                  ? `+ $${open.meta.shippingUsd.toFixed(2)} shipping`
                  : "FREE shipping"}{" "}
                · tax at checkout
              </p>
              <button className="mt-3 w-full rounded-xl bg-ask px-4 py-2 text-sm font-semibold text-zinc-900">
                Add to cart
              </button>
            </Card>
            {agentEye && (
              <Card title="What the agent actually gets" className="border-void/40">
                <p className="text-xs text-muted">
                  Family:{" "}
                  <Pill tone={open.meta.family === "benign" ? "good" : "bad"}>
                    {open.meta.family}
                  </Pill>
                </p>
                {open.meta.hidden && (
                  <p className="mt-2 text-sm text-void">
                    Hidden in {open.meta.hidden.placement}: “{open.meta.hidden.text}”
                  </p>
                )}
                {open.meta.checkoutExtras?.lines.map((l) => (
                  <p key={l.name} className="mt-2 text-sm text-void">
                    Added at checkout: {l.name} (${l.unitUsd.toFixed(2)})
                  </p>
                ))}
                {open.meta.checkoutExtras?.feesUsd?.handling && (
                  <p className="mt-2 text-sm text-void">
                    Handling fee at checkout: $
                    {open.meta.checkoutExtras.feesUsd.handling.toFixed(2)}
                  </p>
                )}
                {open.meta.checkoutExtras?.feesUsd?.insurance && (
                  <p className="mt-2 text-sm text-void">
                    “Shipping insurance” at checkout: $
                    {open.meta.checkoutExtras.feesUsd.insurance.toFixed(2)}
                  </p>
                )}
                {open.meta.family === "benign" && (
                  <p className="mt-2 text-sm">Nothing hidden. What you see is what you get.</p>
                )}
                <details className="mt-3 text-xs">
                  <summary className="cursor-pointer text-muted">
                    Raw page text the agent reads
                  </summary>
                  <pre className="mt-2 max-h-64 overflow-auto whitespace-pre-wrap rounded-lg bg-panel p-2">
                    {open.page.pageText}
                  </pre>
                </details>
              </Card>
            )}
          </div>
        </div>
      )}

      {!cards && !error && <Spinner />}
      <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-3">
        {cards?.map((c) => (
          <button
            key={c.sku}
            onClick={() => void view(c.sku)}
            className="group rounded-2xl border border-line bg-white p-4 text-left shadow-sm transition hover:shadow-md dark:bg-zinc-900"
          >
            <div className="mb-3 h-28 rounded-xl bg-gradient-to-br from-line to-brand-soft" />
            <p className="line-clamp-2 text-sm font-medium group-hover:text-brand">{c.title}</p>
            <p className="mt-1 text-xs text-muted">{c.merchantName}</p>
            <p className="mt-1 text-xs text-ask">
              {stars(c.rating)} <span className="text-muted">{c.rating}</span>
            </p>
            <div className="mt-2 flex items-center justify-between">
              <span className="text-lg font-semibold">${c.priceUsd.toFixed(2)}</span>
              {c.badge && <Pill tone="brand">{c.badge}</Pill>}
            </div>
          </button>
        ))}
      </div>

      <button
        onClick={() => setAgentEye(!agentEye)}
        className={cx(
          "fixed bottom-6 right-6 z-30 rounded-full px-5 py-3 text-sm font-semibold shadow-lg",
          agentEye ? "bg-void text-white" : "bg-ink text-panel",
        )}
      >
        {agentEye ? "Agent's-eye view: ON" : "Agent's-eye view"}
      </button>
    </div>
  );
}
